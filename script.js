let currentCat = 'all';
let searchQuery = '';

function getCatLabel(cat) {
  return { travel: 'السياحة', nature: 'الطبيعة', tech: 'معلوماتية', all: 'الكل' }[cat] || cat;
}

function renderCards(articles) {
  const grid = document.getElementById('articlesGrid');
  const count = document.getElementById('articleCount');
  count.textContent = articles.length + ' مقال';

  if (articles.length === 0) {
    grid.innerHTML = `
      <div class="empty-state">
        <span class="big-icon">🔍</span>
        <p>لا توجد مقالات تطابق بحثك</p>
      </div>`;
    return;
  }

  grid.innerHTML = articles.map((a, i) => `
    <a class="article-card" href="article.html?id=${a.id}" style="animation-delay:${i * 0.07}s">
      <img
        class="card-img"
        src="${a.img}"
        alt="${a.title}"
        loading="lazy"
        onerror="this.style.display='none';this.nextElementSibling.style.display='flex'"
      >
      <div class="card-img-placeholder"
        style="background:${a.cat === 'nature' ? 'var(--forest-soft)' : a.cat === 'tech' ? 'var(--sky-soft)' : a.cat === 'travel' ? 'var(--accent-soft)' : 'var(--paper-warm)'}">
        ${a.cat === 'nature' ? '🌿' : a.cat === 'tech' ? '💻' : a.cat === 'travel' ? '✈️' : '📖'}
      </div>
      <div class="card-body">
        <span class="card-cat cat-${a.cat}">${getCatLabel(a.cat)}</span>
        <h3 class="card-title">${a.title}</h3>
        <p class="card-excerpt">${a.excerpt}</p>
      </div>
      <div class="card-footer">
        <span class="card-date">
          <svg width="13" height="13" viewBox="0 0 24 24" fill="none" stroke="currentColor" stroke-width="2">
            <rect x="3" y="4" width="18" height="18" rx="2"/>
            <line x1="16" y1="2" x2="16" y2="6"/>
            <line x1="8" y1="2" x2="8" y2="6"/>
            <line x1="3" y1="10" x2="21" y2="10"/>
          </svg>
          ${a.date}
        </span>
        <span>⏱ ${a.readTime}</span>
      </div>
    </a>
  `).join('');
}

function filterAndRender() {
  let filtered = ARTICLES;
  if (currentCat !== 'all') {
    filtered = filtered.filter(a => a.cat === currentCat);
  }
  if (searchQuery.trim()) {
    const q = searchQuery.trim().toLowerCase();
    filtered = filtered.filter(a =>
      a.title.includes(q) || a.excerpt.includes(q) || a.author.includes(q)
    );
  }
  const titles = {
    all: 'جميع المقالات',
    travel: 'مقالات السياحة',
    nature: 'مقالات الطبيعة',
    tech: 'مقالات المعلوماتية'
  };
  document.getElementById('sectionTitle').textContent = titles[currentCat] || 'المقالات';
  renderCards(filtered);
}

document.querySelectorAll('.cat-btn').forEach(btn => {
  btn.addEventListener('click', () => {
    document.querySelectorAll('.cat-btn').forEach(b => b.classList.remove('active'));
    btn.classList.add('active');
    currentCat = btn.dataset.cat;
    filterAndRender();
  });
});

document.getElementById('searchInput').addEventListener('input', e => {
  searchQuery = e.target.value;
  filterAndRender();
});

filterAndRender();